  let lastTrigger = null;

  function lookup(dictionary, path) {
    const parts = path.split('.');
    let value = dictionary;
    for (const part of parts) {
      if (value == null) return undefined;
      if (Array.isArray(value) && (part === 'title' || part === 'description')) {
        value = value[part === 'title' ? 0 : 1];
      } else {
        value = value[part];
      }
    }
    return value;
  }

  function lang() {
    return window.DewiPortfolio && window.DewiPortfolio.getLanguage
      ? window.DewiPortfolio.getLanguage() : language;
  }

  function applyLanguage(requested) {
    language = Object.prototype.hasOwnProperty.call(D, requested) ? requested : 'id';
    const dict = D[language];
    document.querySelectorAll('[data-int-i18n]').forEach((element) => {
      const value = lookup(dict, element.dataset.intI18n);
      if (typeof value === 'string') element.textContent = value;
    });
    document.querySelectorAll('[data-int-i18n-alt]').forEach((image) => {
      const value = lookup(dict, image.dataset.intI18nAlt);
      if (typeof value === 'string') image.alt = value;
    });
    document.querySelectorAll('[data-int-i18n-aria]').forEach((element) => {
      const value = lookup(dict, element.dataset.intI18nAria);
      if (typeof value === 'string') element.setAttribute('aria-label', value);
    });
    const dialog = document.getElementById('int-photo-dialog');
    if (dialog) dialog.setAttribute('aria-label', dict.lightboxLabel);
    document.title = dict.pageTitle;
    const projectLink = document.querySelector('.int-project-link');
    if (projectLink) projectLink.setAttribute('aria-label', language === 'en' ? 'View K-Means project' : 'Lihat halaman proyek K-Means');
    updateLightbox();
  }

  function updateLightbox() {
    const image = document.getElementById('int-lightbox-image');
    const caption = document.getElementById('int-lightbox-caption');
    const counter = document.getElementById('int-lightbox-count');
    if (!image || !caption || !counter) return;
    const dict = D[language];
    image.src = gallery[current];
    const alt = current === 0 ? dict.hrga.imageAlt : dict.polres.imageAlts[current - 1];
    const label = current === 0 ? dict.hrga.imageCaption : dict.polres.imageCaptions[current - 1];
    image.alt = alt;
    caption.textContent = label;
    counter.textContent = dict.photoCount.replace('{current}', String(current + 1)).replace('{total}', String(gallery.length));
  }

  function initGallery() {
    const dialog = document.getElementById('int-photo-dialog');
    if (!dialog) return;
    const close = dialog.querySelector('.int-lightbox-close');
    const next = dialog.querySelector('.int-lightbox-next');
    const prev = dialog.querySelector('.int-lightbox-prev');
    document.querySelectorAll('[data-int-photo]').forEach((trigger) => {
      trigger.addEventListener('click', () => {
        current = Math.max(0, Math.min(gallery.length - 1, Number(trigger.dataset.intPhoto) || 0));
        lastTrigger = trigger;
        updateLightbox();
        if (typeof dialog.showModal === 'function') dialog.showModal();
      });
    });
    function step(direction) {
      current = (current + direction + gallery.length) % gallery.length;
      updateLightbox();
    }
    close.addEventListener('click', () => dialog.close());
    next.addEventListener('click', () => step(1));
    prev.addEventListener('click', () => step(-1));
    dialog.addEventListener('click', (event) => {
      if (event.target === dialog) dialog.close();
    });
    dialog.addEventListener('keydown', (event) => {
      if (event.key === 'ArrowRight') { event.preventDefault(); step(1); }
      if (event.key === 'ArrowLeft') { event.preventDefault(); step(-1); }
    });
    dialog.addEventListener('close', () => {
      if (lastTrigger && lastTrigger.isConnected) lastTrigger.focus();
    });
  }

  function initReveal() {
    const page = document.querySelector('#experience .int-page');
    if (!page) return;
    const items = page.querySelectorAll('[data-int-reveal]');
    if (!items.length || !('IntersectionObserver' in window) || window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
    const root = window.matchMedia('(max-width: 760px)').matches ? null : document.getElementById('main-content');
    const observer = new IntersectionObserver((entries, currentObserver) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add('int-visible');
          currentObserver.unobserve(entry.target);
        }
      });
    }, { root, threshold: 0.08, rootMargin: '0px 0px -24px 0px' });
    page.classList.add('int-motion-ready');
    items.forEach((item) => observer.observe(item));
  }

  document.addEventListener('dewi:languagechange', (event) => {
    applyLanguage(event.detail && event.detail.language);
  });
  document.addEventListener('DOMContentLoaded', () => {
    applyLanguage(lang());
    initGallery();
    initReveal();
  });
